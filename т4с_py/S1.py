from datetime import datetime  # Импорт класса datetime из модуля datetime для получения текущего времени и измерения интервалов.

from math import sqrt          # Импорт функции sqrt (square root) из модуля math для вычисления квадратного корня sqrt(x).

def main(**kwargs):            # Объявление функции main, принимающей произвольное количество именованных аргументов.
                               # **kwargs собирает все переданные именованные аргументы в словарь
    """
    Функция main принимает именованные аргументы (каждый — последовательность из двух чисел,
    например [x, y]) и для каждого аргумента вычисляет длину вектора по формуле sqrt(x^2 + y^2).
    """
    for key in kwargs.items(): # Итерация по элементам словаря kwargs. kwargs.items() возвращает последовательность кортежей (ключ, значение).
                               # На каждой итерации переменная key — это кортеж вида (имя_параметра, значение_параметра).

        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)
                               # key[1] - это значение из кортежа.
                               # key[1][0] - первый элемент (x), key[1][1] — второй элемент (y).
                               # Выражение ** 2 возводит в квадрат: x**2 + y**2.
                               # sqrt(...) берёт квадратный корень от суммы — получается длина вектора от (0,0) до (x,y).
        print(result)          # Печатаем вычисленный результат в консоль.

if __name__ == '__main__':
    start_time = datetime.now()  # Сохраняем текущее время до запуска вычислений.
                                 # Объект start_time — экземпляр datetime, хранит дату и время.

    main(                        # Вызов функции main с передачей нескольких именованных аргументов.
        one=[10, 3],             # Именованный аргумент 'one' со значением списка [10, 3] — координаты вектора.
        two=[5, 4],              # 'two' - [5, 4]
        three=[15, 13],          # 'three' - [15, 13]
        four=[93, 53],           # 'four' - [93, 53]
        five=[133, 15]           # 'five' - [133, 15]
    )

    time_costs = datetime.now() - start_time
                                 # Получаем текущее время и вычитаем start_time.
                                 # Результат - объект timedelta, представляющий длительность выполнения main().
    print(f"Время выполнения программы - {time_costs}")
                                 # Выводим строку с информацией о затраченном времени.
                                 # f-строка подставляет значение time_costs в строку.